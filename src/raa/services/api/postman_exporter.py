"""Postman Collection v2.1 exporter for reverse-engineered Android APIs."""

from __future__ import annotations

import json
import uuid
from typing import Any


def export_to_postman_collection(
    project_id: str,
    operations: list[dict[str, Any]],
    collection_name: str | None = None,
    base_url_variable: str = "baseUrl",
) -> str:
    """Format operations into an importable Postman Collection v2.1 JSON string."""
    name = collection_name or f"RAA Project {project_id} API Collection"
    items: list[dict[str, Any]] = []

    for op in operations:
        method = op.get("method", "GET").upper()
        path = op.get("path", "/")
        op_id = op.get("operation_id", f"{method.lower()}_{path.replace('/', '_')}")
        description = op.get("summary", f"{method} {path}")

        # Split path segments for Postman format
        path_segments = [s for s in path.strip("/").split("/") if s]

        headers: list[dict[str, str]] = []
        auth_type = op.get("auth", "none")
        if auth_type == "bearer":
            headers.append(
                {"key": "Authorization", "value": "Bearer {{authToken}}", "type": "text"}
            )
        elif auth_type == "api_key":
            headers.append({"key": "X-API-Key", "value": "{{apiKey}}", "type": "text"})

        request_obj: dict[str, Any] = {
            "method": method,
            "header": headers,
            "url": {
                "raw": f"{{{{{base_url_variable}}}}}{path}",
                "host": [f"{{{{{base_url_variable}}}}}"],
                "path": path_segments,
            },
            "description": description,
        }

        # Include body template for mutating requests
        if method in ("POST", "PUT", "PATCH"):
            request_obj["body"] = {
                "mode": "raw",
                "raw": json.dumps(op.get("sample_body", {}), indent=2),
                "options": {"raw": {"language": "json"}},
            }

        items.append(
            {
                "name": op_id,
                "request": request_obj,
                "response": [],
            }
        )

    collection: dict[str, Any] = {
        "info": {
            "_postman_id": str(uuid.uuid4()),
            "name": name,
            "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
            "description": "Generated by RAA API Reverse Engineering Studio from evidence.",
        },
        "item": items,
        "variable": [
            {
                "key": base_url_variable,
                "value": "https://api.example.com",
                "type": "string",
            },
            {
                "key": "authToken",
                "value": "your_token_here",
                "type": "string",
            },
        ],
    }

    return json.dumps(collection, indent=2)
