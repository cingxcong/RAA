"""Standardized repository-level AGENTS.md contract generator for rebuilt APK projects.

Inspired by Android NowInAndroid architectural conventions. Generates comprehensive AGENTS.md
specifications for external coding agents (Claude Code, Cursor, Android Studio Agent).
"""

from __future__ import annotations

import hashlib
import time
from pathlib import Path
from typing import Any


def generate_agents_spec(
    project_id: str | None = None,
    project_dir: str | None = None,
    app_name: str = "ModernizedApp",
    output_path: str | None = None,
) -> dict[str, Any]:
    """Generate standardized repository-level AGENTS.md contract for rebuilt projects."""
    timestamp = int(time.time())
    sig = hashlib.sha256(f"{project_id}:{app_name}:{timestamp}".encode()).hexdigest()[:8]
    doc_id = f"agents-spec-{sig}"

    markdown_content = f"""# {app_name} — Agent Automation & Architecture Guidelines

> Generated by RAA (Reverse Android Anything) Platform
> Contract ID: `{doc_id}` | Timestamp: `{timestamp}`

## 1. Project Overview & Architecture
- **Framework:** Modern Android Jetpack (Compose + Kotlin Coroutines + Flow)
- **Architecture Pattern:** Unidirectional Data Flow (MVI / MVVM with StateFlow)
- **Dependency Injection:** Hilt / Koin
- **Network Layer:** Retrofit 2 + OkHttp 4 with Moshi / Kotlinx.serialization
- **Local Persistence:** Room Database + DataStore Preferences

## 2. Agent Operational Rules
When modifying or adding features to this codebase, AI coding assistants MUST adhere to:
1. **Compose-First UI:** Do not introduce XML layout files. Use Jetpack Compose.
2. **Deterministic Previews:** Every `@Composable` screen must include an `@Preview`.
3. **Immutability:** Data models must be immutable `@Immutable` Kotlin data classes.
4. **Security Compliance:** Never disable TLS verification or allow cleartext HTTP.

## 3. Standard Build & Verification Commands
- **Assemble Debug APK:** `./gradlew assembleDebug`
- **Run Unit Tests:** `./gradlew testDebugUnitTest`
- **Run UI Instrumentation:** `./gradlew connectedAndroidTest`
- **Lint Check:** `./gradlew lintDebug`
- **Verify Signatures:** `raa rebuild verify-signature --apk build/outputs/apk/app.apk`

## 4. MCP Tools Integration
This repository integrates with the **RAA Model Context Protocol**:
- Use `dyn_gui_state_verify` to validate UI state transitions after modifying screens.
- Use `sec_source_code_review` prior to committing architectural changes.
- Use `rebuild_elf_align_16kb` whenever adding third-party native `.so` prebuilts.
"""

    saved_path: str | None = None
    if output_path:
        out_file = Path(output_path)
        out_file.parent.mkdir(parents=True, exist_ok=True)
        out_file.write_text(markdown_content, encoding="utf-8")
        saved_path = str(out_file)

    return {
        "spec_id": doc_id,
        "app_name": app_name,
        "architecture_pattern": "Unidirectional Data Flow (MVI/MVVM + Compose)",
        "build_system": "Gradle (Kotlin DSL)",
        "output_path": saved_path,
        "document_size_bytes": len(markdown_content.encode("utf-8")),
        "agents_md_preview": markdown_content[:280] + "...",
        "generated_at": timestamp,
    }
